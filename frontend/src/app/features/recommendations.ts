import { Component, computed, DestroyRef, inject, signal } from "@angular/core";
import { ActivatedRoute, RouterLink } from "@angular/router";
import { takeUntilDestroyed } from "@angular/core/rxjs-interop";
import { RunStore } from "./run-store";
import { Recommendation } from "../core/models";
import { Icon, LabelPipe, Notices, State, Status } from "../shared/ui";
import { CoverageNotice } from "../shared/coverage-notice";
export function contentBrief(item: Recommendation): string {
  return `# ${item.title}\n\nTarget query: ${item.query}\nPriority: ${item.priority}\nFormat: ${item.content_type.replaceAll("_", " ")}\n\nAngle\n${item.angle}\n\nVisibility gap\n${item.gap_explanation}\n\nRecommended action\n${item.recommended_action}\n\nEvidence\n${item.supporting_observations.map((o) => `- ${o.surface}: ${o.summary}`).join("\n")}\n\nLimitations\n${item.limitations ?? "Review the underlying measurements before publishing."}\n\nGenerated by: ${item.generated_by}`;
}
@Component({
  imports: [RouterLink, Icon, LabelPipe, State, Status, CoverageNotice],
  templateUrl: "./recommendations.html",
})
export class Recommendations {
  readonly store = inject(RunStore);
  private readonly notices = inject(Notices);
  readonly search = signal("");
  readonly priority = signal("all");
  readonly opportunity = signal<string | null>(null);
  readonly copied = signal<string | null>(null);
  readonly copyFallback = signal("");
  readonly filtered = computed(() =>
    (this.store.report()?.recommendations ?? []).filter(
      (r) =>
        (this.priority() === "all" || r.priority === this.priority()) &&
        (!this.opportunity() || r.opportunity_id === this.opportunity()) &&
        `${r.query} ${r.title} ${r.content_type}`
          .toLowerCase()
          .includes(this.search().toLowerCase()),
    ),
  );
  constructor() {
    inject(ActivatedRoute)
      .queryParamMap.pipe(takeUntilDestroyed())
      .subscribe((params) => this.opportunity.set(params.get("opportunity")));
  }
  inputValue(event: Event) {
    return (event.target as HTMLInputElement).value;
  }
  async copy(item: Recommendation) {
    const brief = contentBrief(item);
    try {
      await navigator.clipboard.writeText(brief);
      this.copied.set(item.id);
      this.copyFallback.set("");
      this.notices.show(
        "Content brief copied. Ready for your content workflow.",
      );
    } catch {
      this.copyFallback.set(brief);
      this.notices.show(
        "Select and copy your brief from the text field below.",
      );
      setTimeout(() => document.getElementById("brief-fallback")?.focus());
    }
  }
  selectText(event: FocusEvent) {
    (event.target as HTMLTextAreaElement).select();
  }
}
